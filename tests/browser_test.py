"""Eldoria end-to-end browser test (headless Chromium via Playwright).
Run: python3 tests/browser_test.py [path/to/index.html]"""
import sys, os
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'file://' + os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'index.html'))
SH = os.environ.get('SHOTS', '/tmp/el_shots'); os.makedirs(SH, exist_ok=True)
res, errs = [], []
def check(n, c, info=''):
    res.append(c); print(('  PASS ' if c else '  FAIL ') + n + ('  [' + str(info) + ']' if info and not c else ''))
def shot(pg, n): pg.screenshot(path=SH + '/' + n + '.png')
def warp(pg, sec):  # fast-forward the world clock by shifting every timer back
    pg.evaluate("""s=>{const S=CH.App.save, d=s*1000; for(const m of S.world.marches){m.t0-=d;m.t1-=d;} for(const k of S.world.kingdoms){k.next-=d;k.nextAtk-=d;}
      for(const b of S.buildings) if(b.job) b.job.ends-=d; for(const k in S.trainJobs) S.trainJobs[k].ends-=d; if(S.healJob) S.healJob.ends-=d; if(S.rjob) S.rjob.ends-=d;}""", sec)

with sync_playwright() as p:
    br = p.chromium.launch(); pg = br.new_page(viewport={'width': 1366, 'height': 800})
    pg.on('pageerror', lambda e: errs.append('pageerror: ' + str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'fonts' not in m.text and 'ERR_NAME' not in m.text else None)
    pg.goto(URL); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(900)
    print('Kingdom')
    check('title screen', pg.is_visible('#t-play'))
    pg.click('#t-play'); pg.wait_for_timeout(300); pg.click('.modal [data-close]'); pg.wait_for_timeout(300)
    check('HUD shows food and the World button', pg.is_visible('#hud-food') and pg.is_visible('[data-dock=world]'))
    pg.click('[data-dock=build]'); pg.wait_for_timeout(300)
    pg.click('[data-act=place][data-type=stoneQuarry]'); pg.wait_for_timeout(200)
    spot = pg.evaluate("(()=>{const s=CH.App.save,a=CH.State.area(s);for(let y=a.y;y<a.y+a.h-1;y++)for(let x=a.x;x<a.x+a.w-1;x++)if(CH.State.tilesFree(s,x,y,2))return {x,y}})()")
    pt = pg.evaluate("([x,y])=>{const v=CH.App.view,r=v.canvas.getBoundingClientRect(),p=v.toScreen((x+1)*32,(y+1)*32);return {x:r.left+p.x,y:r.top+p.y}}", [spot['x'], spot['y']])
    pg.mouse.move(pt['x'], pt['y']); pg.mouse.click(pt['x'], pt['y']); pg.wait_for_timeout(300)
    check('building placed with a builder timer', pg.evaluate("!!CH.App.save.buildings.find(b=>b.type==='stoneQuarry'&&b.job)"))
    pg.click('[data-dock=army]'); pg.wait_for_timeout(300)
    pg.fill('[data-amt=swordsman]', '40'); pg.click('[data-act=train][data-t=swordsman]'); pg.wait_for_timeout(200)
    check('batch training started (costs food)', pg.evaluate("!!CH.App.save.trainJobs.barracks && CH.App.save.trainJobs.barracks.n===40"))
    shot(pg, 'army')
    pg.click('[data-act=tab][data-b=archeryRange]'); pg.wait_for_timeout(200)
    check('army tabs per training building', 'Archer' in pg.inner_text('.troop-grid'))
    pg.click('[data-back]'); pg.wait_for_timeout(200)
    print('World map')
    pg.click('[data-dock=world]'); pg.wait_for_timeout(700); shot(pg, 'world')
    check('world map opens on your castle', pg.evaluate("CH.App.mode==='world'") and pg.is_visible('#wcv'))
    k = pg.evaluate("(()=>{const w=CH.App.save.world;const k=w.kingdoms.filter(k=>k.cl<=2).sort((a,b)=>Math.hypot(a.x-w.px,a.y-w.py)-Math.hypot(b.x-w.px,b.y-w.py))[0];CH.App.wview.center(k.x,k.y);return {id:k.id,x:k.x,y:k.y,name:k.name}})()")
    pg.wait_for_timeout(200)
    sp = pg.evaluate("k=>{const v=CH.App.wview,r=v.canvas.getBoundingClientRect(),p=v.toScreen((k.x+0.5)*48,(k.y+0.5)*48);return {x:r.left+p.x,y:r.top+p.y}}", k)
    pg.mouse.click(sp['x'], sp['y']); pg.wait_for_timeout(300); shot(pg, 'panel')
    check('tapping a kingdom on the map opens its panel', pg.is_visible('#wpanel') and k['name'] in pg.inner_text('#wpanel'))
    pg.click('[data-p=scout]'); pg.wait_for_timeout(200)
    check('scout march sent', pg.evaluate("CH.App.save.world.marches.some(m=>m.owner==='player'&&m.kind==='scout')"))
    pg.mouse.click(sp['x'], sp['y']); pg.wait_for_timeout(200)
    pg.click('[data-p=attack]'); pg.wait_for_timeout(400); shot(pg, 'march')
    check('march dialog with troops, hero and formation', pg.is_visible('.m-list') and pg.is_visible('[data-form=pincer]'))
    pg.click('[data-form=spearhead]'); pg.click('[data-send]'); pg.wait_for_timeout(300)
    check('attack march sent, troops left home', pg.evaluate("CH.App.save.world.marches.some(m=>m.owner==='player'&&m.kind==='attack'&&m.formation==='spearhead')"))
    pg.click('[data-b=toggle]'); pg.wait_for_timeout(200)
    check('marches drawer lists the march with recall', pg.is_visible('.m-drawer') and pg.locator('[data-b=recall]').count() >= 1)
    shot(pg, 'marching')
    warp(pg, 600); pg.wait_for_timeout(1500)
    reps = pg.evaluate("CH.App.save.reports.map(r=>r.kind)")
    check('scout and battle reports arrive', 'scout' in reps and 'attack' in reps, reps)
    pg.click('[data-w=mail]'); pg.wait_for_timeout(300); shot(pg, 'mail')
    pg.locator('.rep-row').filter(has_text='at ').first.click(); pg.wait_for_timeout(400); shot(pg, 'report')
    check('battle report shows both sides and a replay', pg.is_visible('.rep-sides') and pg.is_visible('[data-r=watch]'))
    pg.click('[data-r=watch]'); pg.wait_for_timeout(2500); shot(pg, 'replay')
    check('replay plays the battle', pg.evaluate("CH.App.mode==='replay' && CH.WorldUI.Replay.b.time>0.5"))
    pg.click('[data-rp=speed]'); pg.click('[data-rp=skip]'); pg.wait_for_timeout(2800)
    check('replay ends with the report', pg.is_visible('.rep-sides'))
    pg.evaluate("CH.UI.closeModal(); CH.UI.closeSheets()"); pg.wait_for_timeout(200)
    print('Being attacked')
    pg.evaluate("""(()=>{const s=CH.App.save; s.createdAt=0; s.shieldUntil=0; const k=s.world.kingdoms[0];
      s.world.marches.push({id:'mtest',owner:k.id,kind:'attack',fx:k.x,fy:k.y,tx:s.world.px,ty:s.world.py,t0:Date.now(),t1:Date.now()+200000,army:{swordsman:200,archer:100},hero:'aldric',heroLevel:1,target:{type:'player'},cargo:{}}); k.out=true;})()""")
    pg.evaluate("CH.WorldUI.close()"); pg.wait_for_timeout(800); shot(pg, 'incoming_banner')
    check('incoming attack banner on the kingdom screen', pg.is_visible('#alert') and 'attacks in' in pg.inner_text('#alert'))
    pg.click('#alert'); pg.wait_for_timeout(300); shot(pg, 'incoming')
    check('incoming warning modal with preparation options', pg.is_visible('[data-i=shield]'))
    pg.evaluate("CH.UI.closeModal()"); warp(pg, 220); pg.wait_for_timeout(1500)
    d = pg.evaluate("(()=>{const r=CH.App.save.reports.find(r=>r.kind==='defense');return r&&{o:r.outcome,replay:!!r.replay}})()")
    check('defense battle resolved on your base with a report', d and d['replay'], d)
    check('recovery shield after the attack', pg.evaluate("CH.App.save.shieldUntil>Date.now()"))
    print('Other systems')
    pg.evaluate("CH.WorldUI.open()"); pg.wait_for_timeout(400)
    pg.evaluate("CH.WorldUI.select({type:'home',o:{x:CH.App.save.world.px,y:CH.App.save.world.py}})"); pg.wait_for_timeout(200)
    for m in pg.evaluate("CH.App.save.world.marches.filter(m=>m.owner==='player').map(m=>m.id)"): pg.evaluate("id=>CH.World.recall(CH.App.save,id)", m)
    pg.evaluate("for(const m of CH.App.save.world.marches) if(m.owner==='player'){m.t0-=1e6;m.t1-=1e6}"); pg.wait_for_timeout(800)
    pos = pg.evaluate("[CH.App.save.world.px,CH.App.save.world.py]")
    pg.evaluate("CH.WorldUI.select({type:'home',o:{x:CH.App.save.world.px,y:CH.App.save.world.py}})"); pg.wait_for_timeout(200)
    pg.click('[data-p=tele-random]'); pg.wait_for_timeout(300)
    check('random teleport moves the castle', pg.evaluate("[CH.App.save.world.px,CH.App.save.world.py]") != pos)
    pg.evaluate("CH.WorldUI.close()"); pg.wait_for_timeout(200)
    pg.evaluate("CH.UI.sheet('redeem')"); pg.fill('#rcode', 'eldoria'); pg.click('[data-act=go]'); pg.wait_for_timeout(300)
    check('redeem code works', pg.is_visible('.modal-card') and 'Welcome to Eldoria' in pg.inner_text('.modal-card'))
    pg.evaluate("CH.UI.closeModal()")
    for sc in ['infirmary', 'bag', 'factions', 'events', 'trade', 'lab', 'heroes', 'profile', 'resources']:
        pg.evaluate("s=>{CH.UI.closeSheets();CH.UI.sheet(s)}", sc); pg.wait_for_timeout(200); shot(pg, 's_' + sc)
        check('screen opens: ' + sc, pg.is_visible('.sheet-body'))
    pg.evaluate("CH.UI.closeSheets()")
    print('Persistence')
    snap = pg.evaluate("JSON.stringify([CH.App.save.world.px, CH.App.save.reports.length, CH.App.save.world.kingdoms[0].res.gold|0])")
    pg.evaluate("CH.App.persist()"); pg.reload(); pg.wait_for_timeout(900)
    after = pg.evaluate("JSON.stringify([CH.App.save.world.px, CH.App.save.reports.length, CH.App.save.world.kingdoms[0].res.gold|0])")
    check('world, reports and AI state survive a reload', snap.split(',')[:2] == after.split(',')[:2], (snap, after))
    print('Phones')
    for name, vp in [('phone', (390, 844)), ('phone_land', (844, 390))]:
        pg.set_viewport_size({'width': vp[0], 'height': vp[1]}); pg.wait_for_timeout(300)
        if pg.is_visible('#t-play'): pg.click('#t-play'); pg.wait_for_timeout(300)
        if pg.is_visible('.modal [data-close]'): pg.click('.modal [data-close]')
        pg.evaluate("CH.UI.closeModal()"); shot(pg, 'home_' + name)
        check('home fits: ' + name, pg.evaluate("(()=>{const d=document.getElementById('dock').getBoundingClientRect();return d.right<=innerWidth+1&&d.bottom<=innerHeight+1})()"))
        pg.evaluate("CH.WorldUI.open()"); pg.wait_for_timeout(400)
        pg.evaluate("(()=>{const w=CH.App.save.world;const k=w.kingdoms[2];CH.App.wview.center(k.x,k.y);CH.WorldUI.select({type:'kingdom',o:k})})()"); pg.wait_for_timeout(300); shot(pg, 'world_' + name)
        check('world panel fits: ' + name, pg.evaluate("(()=>{const p=document.getElementById('wpanel').getBoundingClientRect();return p.right<=innerWidth+1&&p.bottom<=innerHeight+1&&p.width>200})()"))
        pg.evaluate("CH.WorldUI.close()"); pg.wait_for_timeout(200)
    br.close()
check('no runtime errors', not errs, errs[:5])
print('\n%d passed, %d failed' % (sum(res), len(res) - sum(res)))
sys.exit(0 if all(res) else 1)
