"""Eldoria progression & invasion browser test.
Run: python3 tests/meta_test.py [path/to/index.html]"""
import sys, os
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'file://' + os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'index.html'))
SH = os.environ.get('SHOTS', '/tmp/meta_shots'); os.makedirs(SH, exist_ok=True)
res, errs = [], []
def check(n, c, i=''): res.append(c); print(('  PASS ' if c else '  FAIL ') + n + (' [' + str(i) + ']' if i and not c else ''))
def shot(pg, n): pg.screenshot(path=SH + '/' + n + '.png')
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1366, 'height': 800})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.add_init_script("(()=>{const _n=Date.now.bind(Date);window.__off=0;Date.now=()=>_n()+window.__off;})()")
    pg.goto(URL); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(800)
    pg.click('#t-play'); pg.wait_for_timeout(300); pg.click('.modal [data-close]'); pg.wait_for_timeout(300)
    pg.evaluate("(()=>{const s=CH.App.save; s.res.gems=5000; s.res.gold=s.res.food=s.res.wood=s.res.stone=300000; s.army={knight:3000,longbowman:2500,heavyCavalry:2000,swordsman:3000}; s.mats={iron:400,leather:400,crystal:80,dragonscale:20}; s.buildings.push({id:9001,type:'embassy',level:3,tx:0,ty:0,buf:0,job:null}); CH.World.joinFaction(s,0)})()")
    print('Daily & login')
    check('HUD shows a Daily button with a badge', pg.is_visible('#hud-daily') and pg.inner_text('#hud-claim') != '')
    pg.click('#hud-daily'); pg.wait_for_timeout(300)
    pg.evaluate("(()=>{const s=CH.App.save,m=CH.Meta.refresh(s);for(const q of m.daily.q)CH.Meta.track(s,CH.Meta.QUESTS.find(x=>x.id===q.id).kind,q.n);CH.UI.refreshSheet()})()"); pg.wait_for_timeout(200)
    shot(pg, 'daily')
    for i in range(5): pg.locator('[data-act=q]').first.click(); pg.wait_for_timeout(120)
    pg.click('[data-act=bonus]'); pg.wait_for_timeout(200)
    check('all five quests and the bonus chest claimed', pg.evaluate("CH.Meta.ensure(CH.App.save).daily.bonus===true"))
    pg.click('[data-act=tab][data-t=login]'); pg.wait_for_timeout(200); shot(pg, 'login')
    pg.click('[data-act=login]'); pg.wait_for_timeout(200)
    check('day-1 login reward claimed', pg.evaluate("CH.Meta.ensure(CH.App.save).login.streak===1"))
    print('Achievements, season, arena, forge')
    pg.wait_for_timeout(800)
    pg.evaluate("CH.UI.closeSheets(); CH.UI.sheet('achievements')"); pg.wait_for_timeout(300)
    pg.evaluate("(()=>{CH.Meta.track(CH.App.save,'raidWin',1);CH.Meta.checkAchievements(CH.App.save);CH.UI.refreshSheet()})()"); pg.wait_for_timeout(200)
    pg.locator('[data-act=wear][data-id=firstBlood]').click(); pg.wait_for_timeout(200); shot(pg, 'achievements')
    check('achievement title worn', pg.evaluate("CH.Meta.titleOf(CH.App.save)") == 'Raider')
    pg.evaluate("CH.UI.closeSheets(); CH.UI.sheet('season')"); pg.wait_for_timeout(300)
    check('season pass gained XP from quests', pg.evaluate("CH.Meta.ensure(CH.App.save).season.xp") >= 600)
    pg.click('[data-act=prem]'); pg.wait_for_timeout(200); pg.locator('[data-act=claim]').first.click(); pg.wait_for_timeout(200); pg.locator('[data-act=claimP]').first.click(); pg.wait_for_timeout(200)
    shot(pg, 'season')
    check('season free + premium rewards claimed', pg.evaluate("(()=>{const se=CH.Meta.ensure(CH.App.save).season;return se.prem&&se.free.length>=1&&se.paid.length>=1})()"))
    pg.evaluate("CH.UI.closeSheets(); CH.UI.sheet('arena')"); pg.wait_for_timeout(300)
    a0 = pg.evaluate("JSON.stringify(CH.App.save.army)")
    pg.click('[data-act=fight]'); pg.wait_for_timeout(600); shot(pg, 'arena_report')
    check('arena fight shows a report and no troops die', pg.is_visible('.rep-sides') and pg.evaluate("JSON.stringify(CH.App.save.army)") == a0)
    pg.evaluate("CH.UI.closeModal(); CH.UI.closeSheets(); CH.UI.sheet('forge','aldric')"); pg.wait_for_timeout(300)
    pg.click('[data-act=craft][data-sl=weapon][data-t="0"]'); pg.wait_for_timeout(200)
    pg.evaluate("CH.App.save.heroes.aldric.level=4; CH.UI.refreshSheet()"); pg.wait_for_timeout(200)
    pg.click('[data-act=tal][data-b=off]'); pg.wait_for_timeout(200); shot(pg, 'forge')
    check('forged and equipped a weapon, spent a talent point', pg.evaluate("CH.Meta.might(CH.App.save,'aldric')") == 5)
    pg.evaluate("CH.UI.closeSheets()")
    print('Diplomacy & nemesis')
    pg.evaluate("CH.WorldUI.open()"); pg.wait_for_timeout(400)
    k = pg.evaluate("(()=>{const w=CH.App.save.world;const k=w.kingdoms.filter(k=>k.f!==0).sort((a,b)=>CH.World.dist(a,{x:w.px,y:w.py})-CH.World.dist(b,{x:w.px,y:w.py}))[0];k.sh=0;CH.App.wview.center(k.x,k.y);CH.WorldUI.select({type:'kingdom',o:k});return k.id})()")
    pg.wait_for_timeout(300); shot(pg, 'diplomacy')
    check('kingdom panel shows diplomacy', pg.is_visible('[data-p=tribute]') and pg.is_visible('[data-p=truce]'))
    pg.click('[data-p=truce]'); pg.wait_for_timeout(300)
    check('truce signed and shown', pg.evaluate("k=>CH.App.save.world.kingdoms.find(x=>x.id===k).truceUntil>Date.now()", k) and pg.is_visible('[data-p=break]'))
    pg.click('[data-p=hire]'); pg.wait_for_timeout(300); shot(pg, 'hire')
    pg.locator('[data-hire]').first.click(); pg.wait_for_timeout(300)
    check('mercenaries hired', pg.evaluate("CH.App.save.world.marches.some(m=>m.hiredBy==='player')"))
    pg.evaluate("(()=>{const s=CH.App.save,k=s.world.kingdoms.find(x=>x.f!==0&&!x.truceUntil);CH.Meta.onPlayerBeat(s,k,Date.now());CH.Meta.onPlayerBeat(s,k,Date.now());CH.Meta.onPlayerBeat(s,k,Date.now());CH.App.wview.center(k.x,k.y);CH.WorldUI.select({type:'kingdom',o:k})})()")
    pg.wait_for_timeout(400); shot(pg, 'nemesis')
    check('nemesis marked on the map panel and a threat letter arrives', 'NEMESIS' in pg.inner_text('#wpanel') and pg.evaluate("CH.App.save.reports.some(r=>r.kind==='letter')"))
    print('Alien Invasion')
    pg.evaluate("(()=>{const s=CH.App.save;CH.Invasion.start(s,Date.now(),'alienInvasion',Date.now()+30*60000);s.shieldUntil=Date.now()+1e9;})()")
    pg.evaluate("window.__off+=31000"); pg.wait_for_timeout(1200)
    check('invasion banner shows waves and kills', pg.is_visible('#warbar') and 'Alien Invasion' in pg.inner_text('#warbar'))
    check('a wave marches on every castle at once', pg.evaluate("CH.App.save.world.marches.filter(m=>m.kind==='invade').length") >= 61)
    pg.evaluate("(()=>{const w=CH.App.save.world;CH.App.wview.center(w.px,w.py);CH.App.wview.cam.zoom=0.32})()"); pg.wait_for_timeout(400); shot(pg, 'invasion_map')
    a1 = pg.evaluate("JSON.stringify(CH.App.save.army)")
    for i in range(14): pg.evaluate("window.__off+=20000"); pg.wait_for_timeout(350)
    rep = pg.evaluate("(()=>{const r=CH.App.save.reports.find(r=>r.kind==='invasion');return r&&r.title})()")
    check('aliens hit your castle: battle report, troops unharmed', rep and pg.evaluate("JSON.stringify(CH.App.save.army)") == a1, rep)
    sh = pg.evaluate("(()=>{const sh=CH.App.save.world.inv.ships[0];CH.App.wview.center(sh.x,sh.y);CH.App.wview.cam.zoom=0.8;CH.WorldUI.select({type:'ship',o:sh});return sh.id})()")
    pg.wait_for_timeout(400); shot(pg, 'mothership')
    pg.click('[data-p=attack]'); pg.wait_for_timeout(300); pg.click('[data-send]'); pg.wait_for_timeout(300)
    left = pg.evaluate("Math.ceil((CH.App.save.world.marches.find(m=>m.owner==='player'&&m.target.type==='ship').t1-Date.now())/1000)")
    pg.evaluate("s=>window.__off+=s*1000", left + 2); pg.wait_for_timeout(1200)
    check('assault on the mothership counted kills', pg.evaluate("CH.App.save.reports.some(r=>r.title.includes('Assault'))"))
    r0 = pg.evaluate("CH.App.save.res.gems")
    pg.evaluate("window.__off+=31*60000"); pg.wait_for_timeout(1500)
    check('invasion ends and pays by kills', pg.evaluate("!CH.App.save.world.inv && CH.App.save.reports.some(r=>r.title.includes('Alien Invasion over'))") and pg.evaluate("CH.App.save.res.gems") > r0)
    pg.evaluate("CH.WorldUI.close(); CH.UI.sheet('events')"); pg.wait_for_timeout(300); shot(pg, 'events_rank')
    check('events screen shows the invasion kill ranking', 'kill ranking' in pg.inner_text('.sheet-body'))
    pg.evaluate("CH.UI.closeSheets()")
    print('King name')
    pg.evaluate("(()=>{const s=CH.App.save;s.world.throne.king={key:'player',name:'Old',f:0,since:Date.now(),until:Date.now()+6e8,held:1};})()")
    pg.evaluate("CH.UI.sheet('profile')"); pg.wait_for_timeout(300)
    pg.fill('#pname', 'Raja Baru'); pg.wait_for_timeout(200)
    pg.evaluate("CH.UI.closeSheets(); CH.WorldUI.open(); const th=CH.App.save.world.throne; CH.WorldUI.select({type:'throne',o:th})"); pg.wait_for_timeout(300)
    check('Citadel shows the renamed king', 'Raja Baru' in pg.inner_text('#wpanel'))
    pg.evaluate("CH.WorldUI.close()")
    print('Phone')
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(300)
    pg.click('[data-dock=more]'); pg.wait_for_timeout(300); shot(pg, 'more_phone')
    check('More menu fits the phone with Daily first', pg.evaluate("(()=>{const d=document.querySelector('[data-more=daily]').getBoundingClientRect(),c=document.querySelector('.modal-card').getBoundingClientRect();return d.top>=0&&c.right<=innerWidth+1})()"))
    pg.evaluate("CH.UI.closeModal(); CH.UI.sheet('season')"); pg.wait_for_timeout(300); shot(pg, 'season_phone')
    b.close()
check('no runtime errors', not errs, errs[:3])
print('\n%d passed, %d failed' % (sum(res), len(res) - sum(res)))
sys.exit(0 if all(res) else 1)
